func fix(s string) string {
	var b strings.Builder
	for _, r := range s {
		b.WriteRune(r)
	}
	return b.String()
}

func es(err error) string {
	if err == nil {
		return ""
	}
	return fix(err.Error())
}

func ebt(t string) string {
	exts, err := mime.ExtensionsByType(t)
	var keep []string
	for _, e := range exts {
		if known[e] {
			keep = append(keep, e)
		}
	}
	return "[" + strings.Join(keep, ",") + "] err=[" + es(err) + "]"
}

func showParams(p map[string]string) string {
	var ks []string
	for k := range p {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	var parts []string
	for _, k := range ks {
		parts = append(parts, k+"="+fix(p[k]))
	}
	return "{" + strings.Join(parts, ";") + "}"
}

func tbe(e string) {
	fmt.Println("TypeByExtension [" + e + "] = [" + mime.TypeByExtension(e) + "]")
}

func ext(e string) {
	fmt.Println("ExtensionsByType [" + e + "] = " + ebt(e))
}

func add(e, t string) {
	err := mime.AddExtensionType(e, t)
	just, _, perr := mime.ParseMediaType(t)
	x := "-"
	if perr == nil {
		x = ebt(just)
	}
	fmt.Println("AddExtensionType [" + e + "] [" + t + "] err=[" + es(err) + "] | [" + mime.TypeByExtension(e) + "] [" + mime.TypeByExtension(strings.ToLower(e)) + "] " + x)
}

func fm(t string, p map[string]string) {
	fmt.Println("FormatMediaType [" + t + "] " + showParams(p) + " = [" + mime.FormatMediaType(t, p) + "]")
}

func parse(s string) {
	m, p, err := mime.ParseMediaType(s)
	fmt.Println("ParseMediaType [" + s + "] = [" + m + "] " + showParams(p) + " err=[" + es(err) + "]")
	if err == nil {
		fp := map[string]string{}
		for k, v := range p {
			fp[k] = fix(v)
		}
		fmt.Println("  -> [" + mime.FormatMediaType(m, fp) + "]")
	}
}

func enc(e mime.WordEncoder, name, cs, s string) {
	fmt.Println("Encode " + name + " " + cs + " [" + s + "] = [" + e.Encode(cs, s) + "]")
}

func dec(w string) {
	d := new(mime.WordDecoder)
	r, err := d.Decode(w)
	fmt.Println("Decode [" + w + "] = [" + fix(r) + "] err=[" + es(err) + "]")
}

func hdr(h string) {
	d := new(mime.WordDecoder)
	r, err := d.DecodeHeader(h)
	fmt.Println("DecodeHeader [" + h + "] = [" + fix(r) + "] err=[" + es(err) + "]")
}

